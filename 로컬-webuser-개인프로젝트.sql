create table zipcode  (
   seq                  NUMBER(10)  not null,
   zipcode              VARCHAR2(50),
   sido                 VARCHAR2(50),
   gugun                VARCHAR2(50),
   dong                 VARCHAR2(50),
   bunji                VARCHAR2(50)
 );
ALTER TABLE zipcode ADD CONSTRAINTS zipcode_SEQ_PK PRIMARY KEY(SEQ);   
ALTER TABLE ZIPCODE MODIFY BUNJI VARCHAR2(100);

--개인 회원가입 테이블
CREATE TABLE CUSTOMER(
    ID          VARCHAR2(15),
    PWD         VARCHAR2(15) NOT NULL,
    NAME        VARCHAR2(15) NOT NULL,
    PHONE1      VARCHAR2(3)   NOT NULL,
    PHONE2      VARCHAR2(4)   NOT NULL,
    PHONE3      VARCHAR2(4)   NOT NULL,
    EMAIL       VARCHAR2(50)   NOT NULL,
    ZIPCODE     VARCHAR2(7)   NOT NULL,
    ADDRESS1    VARCHAR2(100)  NOT NULL,
    ADDRESS2    VARCHAR2(50)    NOT NULL
);
ALTER TABLE CUSTOMER ADD CONSTRAINTS CUSTOMER_ID_PK PRIMARY KEY(ID); 

--공지사항 게시판
CREATE TABLE  NOTICE (
    NUM     NUMBER(7,0) NOT NULL, 
    WRITER  VARCHAR2(12) NOT NULL, 
    EMAIL   VARCHAR2(30) NOT NULL, 
    SUBJECT VARCHAR2(50) NOT NULL, 
    PASS    VARCHAR2(10) NOT NULL, 
    READCOUNT NUMBER(5,0) DEFAULT 0, 
    "REF"   NUMBER(5,0) DEFAULT 0, 
    STEP    NUMBER(3,0) DEFAULT 0, 
    "DEPTH" NUMBER(3,0) DEFAULT 0, 
    REGDATE TIMESTAMP (6) DEFAULT SYSDATE, 
    "CONTENT" VARCHAR2(4000) NOT NULL, 
    IP      VARCHAR2(20) NOT NULL
   );
ALTER TABLE NOTICE ADD CONSTRAINTS NOTICE_NUM_PK PRIMARY KEY(NUM); 

CREATE SEQUENCE NOTICE_SEQ  
   START WITH 1                
   INCREMENT BY 1            
   NOMAXVALUE               
   NOCACHE
   NOCYCLE;
   
